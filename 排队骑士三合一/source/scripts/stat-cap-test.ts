import { card, equipStats, summonInfo } from '../src/core/data';
import { simulate } from '../src/core/engine';
import { previewEndTurn } from '../src/core/previews';
import { newRun, ownedAtk, ownedHp, shownStats, playerTeam, useFood, endTurn, fight, settleBattle, save, load, type Owned } from '../src/core/run';

const ok = (value: unknown, label: string) => { if (!value) throw new Error(label); };
const mk = (oid: number, def = 's_fox'): Owned => ({ oid, def, copies: 1, atkBonus: 60, hpBonus: 70 });
const r = newRun(143, { solo: true }); r.gold = 99;
r.queue[0] = mk(r.nextId++); r.queue[0]!.ench = 'b_buckler';
let o = r.queue[0]!;
ok(shownStats(o)[0] === ownedAtk(o) && shownStats(o)[1] === ownedHp(o), 'equipment must not truncate permanent stats at 50');
r.shop.push({ sid: r.nextId++, kind: 'food', def: 'f_bread', free: false, locked: false });
const before = ownedHp(o);
ok(useFood(r, r.shop.at(-1)!.sid, 0).ok && ownedHp(r.queue[0]!) > before, 'permanent food growth continues above 50');
o = r.queue[0]!;
o.tmpAtk = 25; o.tmpHp = 30;
const team = playerTeam(r);
ok(team[0].atk === ownedAtk(o) + 25 && team[0].hp === ownedHp(o) + 30, 'temporary growth survives equipment conversion');
const rage = equipStats('c_rage', 120, 151);
ok(rage[0] === 120 && rage[1] === 76, 'equipment curse still halves health above 50');
const snapshot = JSON.stringify(r);
const combat = simulate(team, [{ def: 'e_skel', lvl: 1, atk: 1, hp: 90 }], 17);
ok(combat.init[0].atk === team[0].atk && combat.init[0].hp === team[0].hp, 'combat copy retains high stats');
ok(combat.events.some(e => e.t === 'dmg' && e.src === 1 && e.n > 50), 'high attack deals more than 50 damage');
ok(JSON.stringify(r) === snapshot, 'combat leaves owned stats intact');
const growth = simulate([{ def: 'e_frostq', lvl: 1, atk: 80, hp: 100 }], [{ def: 'e_skel', lvl: 1, atk: 1, hp: 300 }], 18);
ok(growth.events.some(e => e.t === 'buff' && e.nowAtk > 80), 'battle growth continues above 50');
const info = summonInfo(card('m_egg'), 1, 1, 80)!;
const summoned = simulate([{ def: 'm_egg', lvl: 1, atk: 1, hp: 1, bank: 80 }], [{ def: 'e_skel', lvl: 1, atk: 1, hp: 200 }], 19);
ok(info.atk === 81 && info.hp === 81 && summoned.events.some(e => e.t === 'summon' && e.unit.atk === info.atk && e.unit.hp === info.hp), 'summon preview and actual summon retain high stats');
r.queue[1] = { ...mk(r.nextId++, 'n_tether'), atkBonus: 0, hpBonus: 0 };
const beforePreview = JSON.stringify(r);
const preview = previewEndTurn(r);
ok(preview[0].after[1] > preview[0].before[1] && !preview[0].capped, 'growth preview does not report a cap at 50');
ok(JSON.stringify(r) === beforePreview && !r.endTurnCommitted, 'preview does not mutate or commit end turn');
endTurn(r);
ok(playerTeam(r)[0].hp === preview[0].after[1], 'preview agrees with actual growth');
const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v), removeItem: (k: string) => storage.delete(k) }, configurable: true });
save(r); const restored = load(); ok(restored, 'high stat save loads');
ok(JSON.stringify(playerTeam(restored!)) === JSON.stringify(playerTeam(r)), 'save round trip retains permanent, temporary and equipment stats');
const out = fight(restored!); ok(out.init[0].atk > 50 && out.init[0].hp > 50, 'restored high stats enter real fight');
settleBattle(restored!, out);
ok(!restored!.queue[0]!.tmpAtk && !restored!.queue[0]!.tmpHp && ownedAtk(restored!.queue[0]!) > 50, 'settlement clears temporary stats and retains permanent growth');
console.log('stat cap checks passed: permanent, temporary, equipment, combat, summon, preview, save and settlement');
