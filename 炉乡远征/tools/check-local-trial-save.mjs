import assert from 'node:assert/strict';
import { SaveManager } from '../dist/js/save-manager.js';
import { createChallengeMatch } from '../dist/js/engine.js';
const KEY = 'duelyst-h5.safe-v1.match';
const storage = { data: new Map([['duelyst-h5.safe-v1.namespace', '{"version":1}']]), removeItem(k) { this.data.delete(k); }, fail: false, getItem(k) { return this.data.get(k) ?? null; }, setItem(k, v) { if (this.fail) throw Error('full'); this.data.set(k, v); } };
const saves = new SaveManager(() => {}, storage);
const match = createChallengeMatch('roar-lethal', []);
assert.equal(saves.saveLocal(match), true);
const saved = storage.getItem(KEY), revision = match.revision;
match.round += 1;
assert.notEqual(saves.localSnapshot.round, match.round, 'persisted snapshot is detached from mutable battle');
storage.fail = true;
assert.equal(saves.saveLocal(match), false);
assert.equal(storage.getItem(KEY), saved);
assert.equal(match.revision, revision, 'failed writes cannot advance revision');
storage.fail = false;
storage.data.set(KEY, '{future-format');
assert.equal(saves.saveLocal(match), false);
assert.equal(storage.getItem(KEY), '{future-format', 'unknown original is never silently replaced');
console.log('local trial save checks passed');
