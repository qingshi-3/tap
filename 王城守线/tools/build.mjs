import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDirectory = fileURLToPath(new URL('../', import.meta.url));
const distDirectory = join(projectDirectory, 'dist');
const sourceFiles = ['levels.js', 'balance.js', 'simulation.js', 'renderer.js', 'audio.js', 'openfield.js', 'openfield-renderer.js', 'openfield-main.js'];
const outputPath = join(distDirectory, 'game.js');

const staticImportPattern = /^\s*import\s+(?:(?:[^'";\r\n]|\r?\n)*?\s+from\s+)?['"][^'"\r\n]+['"]\s*;[ \t]*(?:\r?\n|$)/gm;
const exportListPattern = /^\s*export\s*(?:\{[\s\S]*?\}|\*\s+from\s+['"][^'"\r\n]+['"])\s*(?:from\s+['"][^'"\r\n]+['"]\s*)?;[ \t]*(?:\r?\n|$)/gm;
const exportedDeclarationPattern = /^(\s*)export\s+(?=(?:async\s+)?function\b|(?:const|let|var|class)\b)/gm;
const moduleDeclarationPattern = /^\s*(?:import(?:\s|\{|\*)|export(?:\s|\{|\*))/m;

function convertModule(source, filename) {
  const converted = source
    .replace(staticImportPattern, '')
    .replace(exportListPattern, '')
    .replace(exportedDeclarationPattern, '$1');

  if (moduleDeclarationPattern.test(converted)) {
    throw new Error(`Unsupported or residual import/export declaration in dist/${filename}`);
  }

  return converted.trimEnd();
}

const sections = [];
for (const filename of sourceFiles) {
  const source = await readFile(join(distDirectory, filename), 'utf8');
  sections.push(`// ---- ${filename} ----\n${convertModule(source, filename)}`);
}

const output = `// Generated by tools/build.mjs. Do not edit directly.\n${sections.join('\n\n')}\n`;

if (moduleDeclarationPattern.test(output)) {
  throw new Error('Generated dist/game.js still contains an import/export declaration.');
}

try {
  new Function(output);
} catch (error) {
  throw new Error(`Generated dist/game.js is not valid classic-script syntax: ${error.message}`, { cause: error });
}

await writeFile(outputPath, output, 'utf8');
console.log(`Built dist/game.js from ${sourceFiles.length} modules (${Buffer.byteLength(output)} bytes).`);
