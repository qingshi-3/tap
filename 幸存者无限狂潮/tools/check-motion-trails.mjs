import assert from 'node:assert/strict';
import {createMotionTrails} from '../dist/motion-trails.js';
const view={camera:{x:0,y:0},width:844,height:390},game=Object.freeze({time:0}),tracker=createMotionTrails();
const item=(x,y=100)=>Object.freeze({key:'a',x,y,angle:0,size:24,style:'blade'});
assert.equal(tracker.update(game,0,[item(100)],view).length,0);
assert.equal(tracker.update(game,.016,[item(110)],view)[0].x,100);
assert.equal(tracker.update(game,.032,[item(110,110)],view)[1].x,110);
const curve=tracker.update(game,.048,[item(100,110)],view);
assert.deepEqual(curve.map(p=>[p.x,p.y]),[[100,100],[110,100],[110,110]]);
assert.deepEqual(tracker.update(game,.048,[item(999,999)],view),curve,'pause freezes samples and ages');
assert.equal(tracker.update(game,.1,[item(100,110)],view).length,3,'stopping emits no extra trail');
assert.equal(tracker.update(game,.17,[item(100,110)],view).length,0,'stationary trail expires');
tracker.update(game,.186,[item(110,110)],view);
assert.equal(tracker.update(game,.202,[item(900,110)],view).length,0,'offscreen track clears');
tracker.update(game,.218,[item(100)],view);tracker.update(game,.234,[item(110)],view);
assert.equal(tracker.update(game,.1,[item(120)],view).length,0,'time rollback clears');
tracker.update(game,.116,[item(130)],view);assert.equal(tracker.update({},.132,[item(140)],view).length,0,'new game identity clears');
assert.equal(tracker.update(game,1,[item(140)],view).length,0,'large time gap clears');
tracker.update(game,1.016,[item(150)],view);assert.equal(tracker.update(game,1.032,[item(160)],{...view,reducedMotion:true}).length,0);
const bounded=createMotionTrails({capacity:4,samplesPerTrack:3});
for(let i=0;i<10;i++)bounded.update(game,i*.016,Array.from({length:20},(_,k)=>({...item(k+i+100),key:String(k)})),view);
assert.ok(bounded.update(game,.16,[],view).length<=12,'bounded tracks and samples');
tracker.destroy();assert.equal(tracker.update(game,2,[item(160)],view).length,0);
console.log('Motion history: actual curved positions, pause/stop/expiry, offscreen, identity/rollback/gap, reduce, destroy and bounded storage passed.');
