import { copyFile, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = "C:/Users/qs/Desktop/游戏素材/duelyst-main (1)/duelyst-main/app";
const manifest = path.join(root, "dist/assets.js");
const { unitAssets } = await import(pathToFileURL(manifest).href);
// Keep the existing Godot-derived unit manifest; only add these reviewed constructs.
for (const [key, name, renderSize] of [
  ["familiarLight", "neutral_golemsteel", 76],
  ["familiarHeavy", "neutral_golemrunesand", 98],
]) {
  const png = path.join(source, "original_resources/units", `${name}.png`);
  const xml = await readFile(path.join(source, "resources/units", `${name}.plist`), "utf8");
  const animations = {};
  const entries = [...xml.matchAll(/<key>([^<]+\.png)<\/key>\s*<dict>([\s\S]*?)<\/dict>/g)]
    .sort((a, b) => a[1].localeCompare(b[1], undefined, { numeric: true }));
  for (const [, frameName, body] of entries) {
    const animationName = frameName.slice(name.length + 1).replace(/_\d+\.png$/, "");
    const geometry = body.match(/<key>frame<\/key>\s*<string>([^<]+)<\/string>/)?.[1];
    const [x, y, w, h] = geometry.match(/\d+/g).map(Number);
    // Reviewed source frames are all untrimmed 80px squares, with no rotation.
    if (w !== 80 || h !== 80 || /<key>rotated<\/key>\s*<true/.test(body)) throw new Error(`Unexpected packed construct frame: ${frameName}`);
    const animation = animations[animationName] ||= { fps: 10, loop: ["idle", "run", "walk"].includes(animationName), frames: [] };
    animation.frames.push({ x, y, w, h, duration: 1 });
  }
  await copyFile(png, path.join(root, "dist/assets/units", `${key}.png`));
  unitAssets[key] = {
    src: `./assets/units/${key}.png`, readableName: key === "familiarLight" ? "轻型灵械" : "重装灵械巨像",
    role: "familiar", sourceIdentity: `Duelyst/${name}`,
    sourceSha256: createHash("sha256").update(await readFile(png)).digest("hex").toUpperCase(),
    renderSize, authoredSize: true, anchor: { x: .5, y: .8 },
    animationAliases: { move: ["run"], cast: ["attack"] }, animations,
  };
}
await writeFile(manifest, `// Generated by tools/extract-assets.mjs; reviewed constructs added by tools/extract-familiar-assets.mjs.\nexport const unitAssets = ${JSON.stringify(unitAssets, null, 2)};\n`);
console.log("Added familiarLight and familiarHeavy; preserved existing units.");
