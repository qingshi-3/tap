import {afterEach,expect,it,vi} from 'vitest';
import prior from './fixtures/prep-save-v0101.json';
import {Battle,simulate} from '../src/core/engine';
import {BOSS_ENCOUNTER_RULES} from '../src/core/encounterRules';
import {buildBattle,beginBattle,finishBattle,allocPoint,CONTENT_VERSION} from '../src/core/run';
import {loadRun,saveRun,SAVE_KEY} from '../src/core/save';
import {previewPreparation} from '../src/core/preparation';
afterEach(()=>vi.unstubAllGlobals());
it('frost boss has bounded disruption even when both armies survive a very long fight',()=>{
 const b=new Battle({player:[{defId:'e_skel',atk:7,hp:9999}],enemy:[{defId:'e_frostq',atk:1,hp:9999}],rules:BOSS_ENCOUNTER_RULES.e_frostq,record:true});
 const out=b.run_();expect(out.fault).toBeUndefined();expect(out.beats).toBeGreaterThan(18);
 expect(out.log.filter(x=>x.ev.t==='chill'&&x.ev.src===2&&x.ev.uid===1)).toHaveLength(2);
 expect(out.log.filter(x=>x.ev.t==='rule'&&x.ev.id==='frostq_barrier')).toHaveLength(1);
});
it('actual 0.10.1 source fixture preserves committed growth, plays, saves, reloads and continues',()=>{
 // Generated by output/sap-rework-v011-20261023/make-save-fixture.ts using the frozen 0.10.1 core.
 const data=new Map([[SAVE_KEY,JSON.stringify(prior)]]);vi.stubGlobal('localStorage',{getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>data.set(k,v),removeItem:(k:string)=>data.delete(k)});
 let loaded=loadRun();if(loaded.kind!=='ok')throw Error('historical load');let r=loaded.run;
 expect(r.contentVersion).toBe(CONTENT_VERSION);expect(r.slots).toEqual(prior.slots);expect(previewPreparation(r).slots[0]!.growth).toEqual({atk:1,hp:1});
 expect(allocPoint(r,0,'block')).toBe(true);expect(previewPreparation(r).slots[0]!.growth).toEqual({atk:1,hp:1});
 const first=simulate(buildBattle(r));expect(first.fault).toBeUndefined();beginBattle(r,first.result,first.gold,first.eggStats);expect(saveRun(r)).toBe(true);
 loaded=loadRun();if(loaded.kind!=='ok')throw Error('settlement load');r=loaded.run;finishBattle(r);expect(r.history).toHaveLength(1);expect(r.slots[0]!.growth).toEqual({atk:1,hp:1});expect(saveRun(r)).toBe(true);
 loaded=loadRun();if(loaded.kind!=='ok')throw Error('continued load');r=loaded.run;
 const second=simulate(buildBattle(r));expect(second.fault).toBeUndefined();beginBattle(r,second.result,second.gold,second.eggStats);finishBattle(r);expect(saveRun(r)).toBe(true);
 loaded=loadRun();if(loaded.kind!=='ok')throw Error('second reload');expect(loaded.run.history).toHaveLength(2);expect(saveRun(loaded.run)).toBe(true);
});
