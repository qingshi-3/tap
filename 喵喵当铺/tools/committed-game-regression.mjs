import assert from 'node:assert/strict';
import * as Core from '../js/game.js';
import {createPersistence, normalizeRun} from '../js/persistence.js';
import {createCommittedGame, publishState} from '../js/committed-game.js';
import {makeScenario} from './decision-fixture.mjs';
import {UPGRADES} from '../js/data.js';
let fail=false; const data=new Map();
const storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>{if(fail)throw Error('quota');data.set(k,v)},removeItem:k=>data.delete(k)};
const locks={request:async(_name,_opts,fn)=>fn({})};
const session=createPersistence({storage,locks}); await session.acquire();
Core.setState(normalizeRun(makeScenario(Core,'patience-buyer'))); session.save(Core.S);
const G=createCommittedGame(Core,session), live=G.S, c=G.current(), item=G.S.shelf[0];
G.buyerLooks(c,item);assert.equal(c.item,item);assert.equal(G.S,live);
const saved=JSON.stringify(G.S),cash=G.S.money,bid=c.bid;
fail=true;assert.throws(()=>G.sellItem(c,bid));assert.equal(JSON.stringify(G.S),saved);assert.equal(c.item,item);
fail=false;G.sellItem(c,bid);assert.equal(G.S.money,cash+bid);assert.equal(G.S.shelf.includes(item),false);assert.equal(c.resolved,true);assert.throws(()=>G.sellItem(c,bid));
const priorCash=G.S.money;assert(G.buyUpgrade(UPGRADES.find(u=>u.id==='guide')));assert(G.S.up.guide);assert.equal(G.S.money,priorCash-UPGRADES.find(u=>u.id==='guide').cost);
const reload=session.load();assert.equal(reload.money,G.S.money);assert.equal(reload.queue[reload.qi].resolved,true);
Core.setState(normalizeRun(makeScenario(Core,'patience-seller')));session.save(Core.S);
const seller=G.current();const old=seller.pat;G.checkSpot(seller,0);assert.equal(seller.pat,old-1);assert.equal(G.current(),seller);
const before=JSON.stringify(G.S);fail=true;assert.throws(()=>G.checkSpot(seller,1));assert.equal(JSON.stringify(G.S),before);fail=false;
const clone=JSON.parse(JSON.stringify(G.S));clone.money+=5;const previous=G.S;publishState(previous,clone);assert.equal(previous.money,clone.money);
const rootCounter=previous.uid;const arrival=JSON.parse(JSON.stringify(previous));arrival.shelf.push({uid:rootCounter,id:'fry',q:1,cost:12,fake:false,stolen:false,known:true});arrival.uid++;
publishState(previous,arrival);assert.equal(previous.shelf.at(-1).id,'fry');assert.notEqual(previous,previous.shelf.at(-1));assert.doesNotThrow(()=>JSON.stringify(previous));
const sold={uid:1,id:'fish',cost:10,q:1},oldDay={uid:2,shelf:[sold],queue:[{item:sold}]};
const newDay={uid:3,shelf:[{...sold}],queue:[{item:{uid:2,id:'can',cost:0,q:1}}]};
publishState(oldDay,newDay);assert.equal(oldDay.shelf[0].id,'fish');assert.equal(oldDay.shelf[0].uid,1);assert.equal(oldDay.queue[0].item.uid,2);assert.notEqual(oldDay.shelf[0],oldDay.queue[0].item);
session.release();console.log('PASS committed legacy actions: references, save failure rollback, sold-customer replay, reload, patience');

